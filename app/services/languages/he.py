def period(h24: int) -> str:
    if 6 <= h24 < 12:
        return "בַּבֹּקֶר"
    if 12 <= h24 < 16:
        return "בַּצָּהֳרַיִם"
    if 16 <= h24 < 18:
        return "אַחַר הַצָּהֳרַיִם"
    if 18 <= h24 < 21:
        return "בָּעֶרֶב"
    if 21 <= h24 < 24 or 0 <= h24 < 3:
        return "בַּלַּיְלָה"
    return "לִפְנוֹת בֹּקֶר"


def time_text(h24: int, m: int) -> tuple[list[str], str]:
    hour = HOURS[(h24 % 12 or 12) - 1]
    minutes = MINUTE_PREFIX[m]
    if len(hour + minutes) > 25:
        return [hour, minutes], period(h24)
    return [f"{hour} {minutes}".strip()], period(h24)


def day_name(weekday: int) -> str:
    return DAYS[weekday]


def date_text(day: int, month: int) -> str:
    return f"{day} {MONTHS[month - 1]}"


def _year_letters(year: int) -> str:
    y = year % 1000
    h, t, u = y // 100, (y % 100) // 10, y % 10
    letters = _HUNDREDS[h]
    tu = t * 10 + u
    if tu == 15:
        letters += "טו"
    elif tu == 16:
        letters += "טז"
    else:
        letters += _TENS[t] + _UNITS[u]
    if len(letters) > 1:
        letters = letters[:-1] + "״" + letters[-1]
    elif len(letters) == 1:
        letters += "׳"
    return letters


def jewish_date(hd: int, hm: str, hy: int) -> tuple[str, str]:
    return f"{_DAY_NUMBERS[hd - 1]} {JEWISH_MONTHS.get(hm, hm)}", _year_letters(hy)


